export function editorLabel(key: string, language?: string): string {
  return (
    labels[key]?.[languageOf(language) === 'nl' ? 1 : 0] ??
    key.replaceAll('_', ' ')
  );
}
export function editorHelper(key: string, language?: string): string {
  return helpers[key]?.[languageOf(language) === 'nl' ? 1 : 0] ?? '';
}
